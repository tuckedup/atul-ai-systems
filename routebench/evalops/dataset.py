"""Versioned records for the calibration corpus.

Four record types live in four append-only JSONL files, joined by `case_id`:

    cases.jsonl        the task, the reference, and the candidate response being graded
    annotations.jsonl  one human (or oracle) pass/fail label per case per annotator
    judgments.jsonl    one automated judgment per case per judge configuration
    splits.json        which case/group belongs to train / dev / test

Keeping labels in a separate file from cases is not bookkeeping fussiness. The judge runner
loads `cases.jsonl` and never opens `annotations.jsonl`, which makes label leakage into a
judge prompt a structural impossibility rather than a code-review promise. The join happens
in `report.py`, after the judge bundle is frozen.

`LabelProvenance` is the field that keeps the final claim honest. The previous corpus was
generated by `generate_data.py`, which wrote the same integer into `human_score` and
`judge_score`; it reported kappa 1.0 and meant nothing. Fixture provenance is therefore a
first-class value that the release gate refuses.
"""
from __future__ import annotations

import hashlib
import json
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from enum import Enum
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field, field_validator

from .taxonomy import canonical

SCHEMA_VERSION = "1.0.0"


class LabelProvenance(str, Enum):
    """Where a pass/fail label came from. The gate treats these very differently."""

    #: A person read the candidate response and judged it. Published expert annotations.
    HUMAN_EXPERT = "human_expert_annotation"
    #: A person in this project hand-labelled it through `evalops/annotate.py`.
    HUMAN_LOCAL = "human_local_annotation"
    #: A human wrote the ground truth (hidden tests, gold SQL, gold final answer) and a
    #: deterministic oracle -- not the judge under test -- compared the candidate to it.
    GOLD_ORACLE = "human_gold_reference_oracle"
    #: Machine-generated agreement. Never admissible as a calibration label.
    FIXTURE = "synthetic_fixture"

    @property
    def admissible(self) -> bool:
        """True if this label may back a published calibration claim."""
        return self is not LabelProvenance.FIXTURE


#: Provenance classes that count as a *human judgment of the response* for the headline claim.
HEADLINE_PROVENANCE = frozenset({LabelProvenance.HUMAN_EXPERT, LabelProvenance.HUMAN_LOCAL})


def content_hash(*parts: Any) -> str:
    h = hashlib.sha256()
    for p in parts:
        h.update(json.dumps(p, sort_keys=True, default=str).encode())
        h.update(b"\x00")
    return h.hexdigest()[:16]


class CaseRecord(BaseModel):
    """One (task, candidate response) pair awaiting a pass/fail verdict."""

    case_id: str
    #: Independent sampling unit. All cases derived from one source document or prompt family
    #: share a group so that splits cannot leak and the bootstrap cannot over-count evidence.
    group_id: str
    task_class: str
    difficulty: str = "medium"
    #: The prompt shown to the model that produced `candidate_output`.
    task_input: str
    #: Supporting material the judge is allowed to cite (source document, schema, table DDL).
    context: str = ""
    #: The verified correct answer. Judges see it; it is not a label.
    reference: str = ""
    reference_provenance: str = ""
    rubric_id: str = ""
    rubric_version: str = ""
    candidate_output: str = ""
    generator_id: str = "unknown"
    source: str = ""
    source_license: str = ""
    origin: str = "real"
    schema_version: str = SCHEMA_VERSION
    meta: dict[str, Any] = Field(default_factory=dict)

    @field_validator("task_class")
    @classmethod
    def _canon(cls, v: str) -> str:
        return canonical(v)

    @field_validator("origin")
    @classmethod
    def _origin(cls, v: str) -> str:
        if v not in ("real", "synthetic_fixture"):
            raise ValueError(f"origin must be 'real' or 'synthetic_fixture', got {v!r}")
        return v

    @property
    def fingerprint(self) -> str:
        return content_hash(self.task_input, self.context, self.reference, self.candidate_output)


class Annotation(BaseModel):
    """One pass/fail label. `label` is binary and is never re-thresholded downstream."""

    case_id: str
    annotator_id: str
    label: int
    provenance: LabelProvenance
    rubric_version: str = ""
    reason: str = ""
    timestamp: str = ""
    #: Set on the record that survived adjudication of a two-rater disagreement.
    adjudicated: bool = False
    original_votes: list[int] = Field(default_factory=list)
    schema_version: str = SCHEMA_VERSION

    @field_validator("label")
    @classmethod
    def _binary(cls, v: int) -> int:
        if v not in (0, 1):
            raise ValueError(f"label must be 0 or 1, got {v!r}")
        return v


class Judgment(BaseModel):
    """One automated verdict, fully bound to the configuration that produced it."""

    case_id: str
    variant_id: str
    #: The model we asked for, and the model the provider actually served. Never assume equal.
    model_requested: str
    model_served: str = ""
    config_hash: str = ""
    rubric_version: str = ""
    raw_score: float | None = None
    criteria: list[dict[str, Any]] = Field(default_factory=list)
    evidence: list[str] = Field(default_factory=list)
    critical_errors: list[str] = Field(default_factory=list)
    rationale: str = ""
    #: Where the judge's cited quotes were actually found, as
    #: `{total, in_source, in_candidate, unlocated, too_short}`. Computed by
    #: `judge.locate_evidence` and persisted here so it can be reported and used as a calibrator
    #: feature. It used to be computed and then dropped on the floor: `ParsedJudgment` carried
    #: `evidence_verbatim`/`evidence_total`, `judge_one` never copied them across, and the comment
    #: claiming "the ratio is reported so the experiment table can show whether it tracks kappa"
    #: described something no code did.
    evidence_location: dict[str, int] = Field(default_factory=dict)
    #: Facts the judge called supported while citing a span that is not in the source material.
    #: Only meaningful for decompose-mode judgments.
    support_unverified: int = 0
    #: "ok" | "parse_error" | "provider_error" | "quota_exhausted" | "invalid_output" | "refused"
    status: str = "ok"
    error: str | None = None
    attempts: int = 1
    prompt_tokens: int = 0
    completion_tokens: int = 0
    cost_usd: float | None = None
    latency_ms: float = 0.0
    trace_id: str = ""
    schema_version: str = SCHEMA_VERSION

    @property
    def usable(self) -> bool:
        """A judgment with a non-ok status is an error, not a score of zero.

        `aisys.evals.run` collapses grader exceptions into `score=0.0`. For a success-rate
        table that is a defensible convention; for calibration it silently converts provider
        timeouts into 'the judge said fail' and biases kappa. Errors stay errors here.
        """
        return self.status == "ok" and self.raw_score is not None


# ---------------- JSONL / JSON io ----------------
def write_jsonl(path: str | Path, records: Iterable[BaseModel]) -> int:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with p.open("w", encoding="utf-8") as stream:
        for r in records:
            stream.write(json.dumps(r.model_dump(mode="json"), sort_keys=True) + "\n")
            count += 1
    return count


def append_jsonl(path: str | Path, records: Iterable[BaseModel]) -> int:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with p.open("a", encoding="utf-8") as stream:
        for r in records:
            stream.write(json.dumps(r.model_dump(mode="json"), sort_keys=True) + "\n")
            count += 1
    return count


def read_jsonl(path: str | Path, model: type[BaseModel]) -> Iterator[Any]:
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"missing dataset file: {p}")
    with p.open(encoding="utf-8") as stream:
        for lineno, line in enumerate(stream, 1):
            line = line.strip()
            if not line:
                continue
            try:
                yield model.model_validate_json(line)
            except Exception as e:
                raise ValueError(f"{p}:{lineno}: invalid {model.__name__}: {e}") from e


@dataclass
class Corpus:
    """Cases plus whatever labels and judgments are on disk, with integrity checks run."""

    cases: list[CaseRecord]
    annotations: list[Annotation]

    @property
    def cases_hash(self) -> str:
        """Digest of the case CONTENTS. This is what `dataset_hash` has always been."""
        return content_hash(sorted(c.fingerprint for c in self.cases))

    @property
    def annotations_hash(self) -> str:
        """Digest of the LABELS: case id, label value and provenance for every annotation.

        Separate from `cases_hash` because a calibration bundle bound only to case contents is
        bound to the questions and not to the answers. Flipping a human label leaves `cases_hash`
        byte-identical, so a relabelled corpus passed the release gate -- and relabelling is the
        single cheapest way to move kappa, which is exactly why `docs/KAPPA_DESIGN.md` §8 lists
        "editing human labels after seeing judge output" first among the things the protocol
        forbids. A forbidden operation with no detector is a convention, not a control.

        `annotator_id` and `adjudicated` are included: which rater produced a label, and whether it
        survived adjudication, are part of what the headline track claims. `reason` and `timestamp`
        are not -- they are commentary, and hashing them would make a typo fix look like tampering.
        """
        return content_hash([
            [a.case_id, a.label, a.provenance.value, a.annotator_id, a.adjudicated]
            for a in sorted(self.annotations, key=lambda a: (a.case_id, a.annotator_id))
        ])

    @classmethod
    def load(cls, root: str | Path, *, require_labels: bool = True) -> Corpus:
        root = Path(root)
        cases = list(read_jsonl(root / "cases.jsonl", CaseRecord))
        if not cases:
            raise ValueError(f"{root / 'cases.jsonl'} contains zero cases")
        ids = [c.case_id for c in cases]
        if len(set(ids)) != len(ids):
            dupes = sorted({i for i in ids if ids.count(i) > 1})
            raise ValueError(f"duplicate case_id values: {dupes[:10]}")
        seen: dict[str, str] = {}
        for c in cases:
            if c.fingerprint in seen:
                raise ValueError(
                    f"cases {seen[c.fingerprint]} and {c.case_id} are byte-identical; "
                    "near-duplicates inflate agreement and must be de-duplicated at build time"
                )
            seen[c.fingerprint] = c.case_id
        annotations: list[Annotation] = []
        path = root / "annotations.jsonl"
        if path.exists():
            annotations = list(read_jsonl(path, Annotation))
        elif require_labels:
            raise FileNotFoundError(f"missing {path}; run evalops/annotate.py to produce labels")
        known = {c.case_id for c in cases}
        orphans = sorted({a.case_id for a in annotations} - known)
        if orphans:
            raise ValueError(f"annotations reference unknown cases: {orphans[:10]}")
        return cls(cases, annotations)

    def by_id(self) -> dict[str, CaseRecord]:
        return {c.case_id: c for c in self.cases}

    def resolved_labels(
        self, *, allow: frozenset[LabelProvenance] | None = None
    ) -> dict[str, Annotation]:
        """One label per case: the adjudicated record if present, else a unanimous vote.

        Cases whose raters disagreed and were never adjudicated are *excluded* rather than
        broken by majority of two. Dropping them is visible; guessing them is not.
        """
        allowed = allow if allow is not None else frozenset(
            p for p in LabelProvenance if p.admissible
        )
        grouped: dict[str, list[Annotation]] = {}
        for a in self.annotations:
            if a.provenance in allowed:
                grouped.setdefault(a.case_id, []).append(a)
        out: dict[str, Annotation] = {}
        for case_id, votes in grouped.items():
            adjudicated = [v for v in votes if v.adjudicated]
            if adjudicated:
                out[case_id] = adjudicated[0]
            elif len({v.label for v in votes}) == 1:
                out[case_id] = votes[0]
        return out

    def label_summary(self) -> dict[str, Any]:
        per: dict[str, int] = {}
        for a in self.annotations:
            per[a.provenance.value] = per.get(a.provenance.value, 0) + 1
        resolved = self.resolved_labels()
        unresolved = sorted(
            {a.case_id for a in self.annotations} - set(resolved) - {""}
        )
        return {
            "n_cases": len(self.cases),
            "n_annotations": len(self.annotations),
            "by_provenance": per,
            "n_resolved": len(resolved),
            "n_unresolved_disagreements": len(unresolved),
            "tasks": sorted({c.task_class for c in self.cases}),
            "n_groups": len({c.group_id for c in self.cases}),
        }
