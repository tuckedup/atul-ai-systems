# ---------------------------------------------------------------- the ladder


def test_uncalibrated_judge_blocks_promotion_despite_high_quality(tmp_path):
    """A great-looking quality score must not ship behind an unvalidated judge."""
    audit = AuditLog(f"sqlite:///{tmp_path}/audit.db")
    result = promote(
        "shiny", 0.99, 0.80, lambda weight: 0.99, audit,
        calibration=_write(tmp_path, _bundle(test_result=None)),
    )
    assert result.blocked_by_calibration and result.stage == "blocked"
    assert not result.history, "the ladder must not run at all when the judge is untrusted"
    event = audit.rows()[-1][2]
    assert event["type"] == "model_promotion" and event["calibration_valid"] is False
    assert event["reasons"], "a blocked promotion must record why"


def test_valid_calibration_allows_full_rollout(tmp_path):
    audit = AuditLog(f"sqlite:///{tmp_path}/audit.db")
    result = promote(
        "good", 0.90, 0.88, lambda weight: 0.90, audit,
        calibration=_write(tmp_path, _bundle()),
    )
    assert result.stage == "full" and not result.rolled_back
    assert [h["stage"] for h in result.history] == ["shadow", "canary-5", "canary-25", "full"]


def test_regression_rolls_back_and_is_audited(tmp_path):
    audit = AuditLog(f"sqlite:///{tmp_path}/audit.db")
    result = promote(
        "worse", 0.9, 0.9, lambda weight: 0.7 if weight >= 0.05 else 0.9, audit,
        calibration=_write(tmp_path, _bundle()),
    )
    assert result.rolled_back and result.stage == "rollback"
    assert audit.rows()[-1][2]["type"] == "model_promotion"


def test_offline_gate_rolls_back_before_any_traffic(tmp_path):
    audit = AuditLog(f"sqlite:///{tmp_path}/audit.db")
    calls: list[float] = []
    result = promote(
        "bad", 0.50, 0.90, lambda weight: calls.append(weight) or 0.9, audit,  # type: ignore[func-returns-value]
        calibration=_write(tmp_path, _bundle()),
    )
    assert result.rolled_back and result.stage == "rollback"
    assert calls == [], "a failed offline gate must not send even shadow traffic"


def test_gate_can_be_skipped_but_the_skip_is_audited(tmp_path):
    audit = AuditLog(f"sqlite:///{tmp_path}/audit.db")
    result = promote("local", 0.9, 0.9, lambda weight: 0.9, audit, calibration=None)
    assert result.stage == "full"
    assert audit.rows()[-1][2]["calibration_checked"] is False


@pytest.mark.parametrize("min_kappa", [0.60, 0.74])
def test_artifact_accepted_at_a_weaker_policy_is_rejected_under_a_stricter_one(tmp_path, min_kappa):
    ok, _ = validate_bundle(_write(tmp_path, _bundle(min_kappa=0.60)), min_kappa=min_kappa)
    assert ok is (min_kappa <= 0.60)
